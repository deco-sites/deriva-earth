// Language management
(function() {
  const STORAGE_KEY = 'deriva_language';
  const DEFAULT_LANG = 'pt';
  
  // Get current language from localStorage or default
  function getCurrentLanguage() {
    try {
      return localStorage.getItem(STORAGE_KEY) || DEFAULT_LANG;
    } catch (e) {
      return DEFAULT_LANG;
    }
  }
  
  // Set language in localStorage
  function setLanguage(lang) {
    try {
      localStorage.setItem(STORAGE_KEY, lang);
    } catch (e) {
      console.error('Error saving language:', e);
    }
  }
  
  // Get translation
  function t(key) {
    const lang = getCurrentLanguage();
    const keys = key.split('.');
    let value = translations[lang];
    
    for (const k of keys) {
      value = value?.[k];
    }
    
    return value || translations[DEFAULT_LANG][key] || key;
  }
  
  // Update all elements with data-i18n attribute
  function updateTranslations() {
    const elements = document.querySelectorAll('[data-i18n]');
    elements.forEach(el => {
      const key = el.getAttribute('data-i18n');
      const translation = t(key);
      
      if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
        if (el.hasAttribute('placeholder')) {
          el.placeholder = translation;
        } else {
          el.value = translation;
        }
      } else if (el.hasAttribute('dangerouslySetInnerHTML') || el.innerHTML !== el.textContent) {
        // Element uses innerHTML (like FAQ answers with rich text)
        el.innerHTML = translation;
      } else {
        el.textContent = translation;
      }
    });
    
    // Update innerHTML for elements with data-i18n-html
    const htmlElements = document.querySelectorAll('[data-i18n-html]');
    htmlElements.forEach(el => {
      const key = el.getAttribute('data-i18n-html');
      const translation = t(key);
      el.innerHTML = translation;
    });
  }
  
  // Initialize language on page load
  function initLanguage() {
    const currentLang = getCurrentLanguage();
    document.documentElement.setAttribute('lang', currentLang);
    updateTranslations();
    
    // Update language selector
    const langSelectors = document.querySelectorAll('[data-lang-selector]');
    langSelectors.forEach(selector => {
      const buttons = selector.querySelectorAll('[data-lang]');
      buttons.forEach(btn => {
        const btnLang = btn.getAttribute('data-lang');
        if (btnLang === currentLang) {
          btn.classList.add('active');
        } else {
          btn.classList.remove('active');
        }
      });
    });
  }
  
  // Change language
  function changeLanguage(lang) {
    if (!translations[lang]) {
      console.error('Invalid language:', lang);
      return;
    }
    
    setLanguage(lang);
    document.documentElement.setAttribute('lang', lang);
    updateTranslations();
    
    // Update language selector
    const langSelectors = document.querySelectorAll('[data-lang-selector]');
    langSelectors.forEach(selector => {
      const buttons = selector.querySelectorAll('[data-lang]');
      buttons.forEach(btn => {
        const btnLang = btn.getAttribute('data-lang');
        if (btnLang === lang) {
          btn.classList.add('active');
        } else {
          btn.classList.remove('active');
        }
      });
    });
    
    // Dispatch custom event
    window.dispatchEvent(new CustomEvent('languageChanged', { detail: { lang } }));
  }
  
  // Expose functions globally
  window.DerivaI18n = {
    t,
    changeLanguage,
    getCurrentLanguage,
    updateTranslations
  };
  
  // Initialize when DOM is ready
  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', initLanguage);
  } else {
    initLanguage();
  }
  
  // Re-initialize on language change
  window.addEventListener('languageChanged', () => {
    updateTranslations();
  });
})();
